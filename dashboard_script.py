import pandas as pd

# Load the raw CSV that already exists in Colab
df = pd.read_csv("dairy_dataset.csv")

# Clean the column names
df.columns = (
    df.columns
    .str.strip()
    .str.lower()
    .str.replace(r"[^\w\s]", "", regex=True)
    .str.replace(r"\s+", "_", regex=True)
)

# Convert all date columns from text into real dates
date_columns = [col for col in df.columns if "date" in col]

for col in date_columns:
    df[col] = pd.to_datetime(df[col], errors="coerce")

# Save the cleaned dataset
df.to_csv("dairy_goods_sales_cleaned.csv", index=False)

# The dataset is historical, so use its latest date for this demo
reference_date = df["expiration_date"].max() - pd.Timedelta(days=7)

LOW_STOCK_THRESHOLD = 20
EXPIRY_WARNING_DAYS = 7

# Create priority flags
df["days_to_expiry"] = (
    df["expiration_date"] - reference_date
).dt.days

df["low_stock_flag"] = (
    df["quantity_in_stock_literskg"] < LOW_STOCK_THRESHOLD
)

df["expiring_soon_flag"] = (
    df["days_to_expiry"].between(0, EXPIRY_WARNING_DAYS)
)

df["critical_flag"] = (
    df["low_stock_flag"] & df["expiring_soon_flag"]
)

# Keep only items needing attention
priority_df = df[
    df["low_stock_flag"] | df["expiring_soon_flag"]
][
    [
        "product_name",
        "brand",
        "quantity_in_stock_literskg",
        "days_to_expiry",
        "low_stock_flag",
        "expiring_soon_flag",
        "critical_flag",
    ]
]

# Put critical items first
priority_df = priority_df.sort_values(
    by=["critical_flag", "days_to_expiry"],
    ascending=[False, True],
)

# Save FreshRoute's priority file
priority_df.to_csv(
    "freshroute_priority_dashboard.csv",
    index=False
)

print("SUCCESS!")
print("Cleaned dataset created: dairy_goods_sales_cleaned.csv")
print("Priority dashboard created: freshroute_priority_dashboard.csv")
print("Priority rows:", len(priority_df))
